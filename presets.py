"""Встроенные пресеты для ИИ-команд.

Пресет — это именованный system-prompt. Здесь только данные: сам вызов модели
живёт в ``openai_service.py`` (инфраструктура), а доставка в Telegram — в
``preset_handlers.py``. Чтобы добавить новый пресет, достаточно описать его
константой и зарегистрировать в ``PRESETS``.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Preset:
    """Именованный system-prompt для отдельной ИИ-команды."""

    name: str
    description: str
    system_prompt: str


IDIOMA = Preset(
    name="idioma",
    description="Перевод: испанский ↔ русский/украинский/английский",
    system_prompt=(
        "Ты переводчик. Определи язык текста.\n"
        "- Если текст на испанском — переведи на русский.\n"
        "- Во всех остальных случаях (русский, украинский, английский, другой) — "
        "переведи на испанский.\n"
        "Верни только перевод: без пояснений, заголовков и кавычек.\n"
        "Не сокращай и не пересказывай — переведи текст целиком, сохраняя смысл, тон и формат.\n"
        "Имена, ссылки и код не переводи."
    ),
)

# Имя пресета -> Preset. Имя совпадает с командой без слэша.
PRESETS: dict[str, Preset] = {preset.name: preset for preset in (IDIOMA,)}
